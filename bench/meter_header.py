#!/usr/bin/env python3
"""Write bench/metered/GeblomiSort.hpp.

Bench-only copy of the amalgam. The product header is not modified.
CountLess is treated as std::less<> for the two routing checks, ska_sort's
std::sort fallback counts comparisons, and current_byte counts digit reads.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "public" / "geblomi-sort" / "GeblomiSort.hpp"
OUT = ROOT / "bench" / "metered" / "GeblomiSort.hpp"

LESS = "std::is_same_v<Compare, std::less<>>"
LESS_METER = (
    "(std::is_same_v<Compare, std::less<>> || "
    "::geb_meter::is_counting_less<Compare>::value)"
)

FALLBACK = (
    "std::sort(begin, end, [&](auto && l, auto && r)"
    "{ return extract_key(l) < extract_key(r); });"
)
FALLBACK_METER = (
    "std::sort(begin, end, [&](auto && l, auto && r)"
    "{ ++::geb_meter::cmp; return extract_key(l) < extract_key(r); });"
)

BYTE = "current_byte(extract_key(*it), sort_data)"
BYTE_METER = "(++::geb_meter::digit, current_byte(extract_key(*it), sort_data))"


def main() -> None:
    text = SRC.read_text()
    n_less = text.count(LESS)
    n_fallback = text.count(FALLBACK)
    n_byte = text.count(BYTE)
    if (n_less, n_fallback, n_byte) != (2, 1, 4):
        raise SystemExit(
            f"REFUSE: meter anchors moved: less={n_less} fallback={n_fallback} byte={n_byte}"
        )
    text = text.replace(LESS, LESS_METER)
    text = text.replace(FALLBACK, FALLBACK_METER)
    text = text.replace(BYTE, BYTE_METER)
    header = (
        "// Generated by bench/meter_header.py from public/geblomi-sort/GeblomiSort.hpp.\n"
        "// Bench-only. Do not include this from product code.\n"
        '#include "../meter.hpp"\n'
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
